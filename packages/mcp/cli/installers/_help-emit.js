/** @module cli/installers/help-emit - the two host sources generated from the help surface */

import { buildHelpSurface, HELP_EVENT, HELP_TOKENS, OPENCODE_HELP_COMMAND } from "./_help-surface.js";

/**
 * The help blocks as a JSON literal for the generated sources.
 *
 * @returns {string}
 */
function helpMapSource() {
  const entries = buildHelpSurface().map((entry) => `  ${JSON.stringify(entry.name)}: ${JSON.stringify(entry.text)},`);

  return `{\n${entries.join("\n")}\n}`;
}

/**
 * The `command  description` list shown when no command is named.
 *
 * @returns {string}
 */
function commandListSource() {
  const lines = buildHelpSurface().map((entry) => `  /${entry.name}  ${entry.description}`);

  return JSON.stringify(`rule-mcp commands:\n\n${lines.join("\n")}\n\nRun /rule-help <command> for one command's usage.`);
}

/**
 * Pi's extension source: one file, auto-discovered from
 * `~/.pi/agent/extensions/`.
 *
 * @returns {string}
 */
export function piHelpExtension() {
  return `/**
 * rule-mcp: \`/<command> help\` answered without a model turn.
 *
 * Generated by \`rule-mcp install --agent pi\` - do not edit, reinstall instead.
 */
import { Text } from "@earendil-works/pi-tui";

const HELP = ${helpMapSource()};

const HELP_EVENT = ${JSON.stringify(HELP_EVENT)};
const HELP_TOKENS = new Set(${JSON.stringify(HELP_TOKENS)});
const CAPTURE = /^\\/([a-z][a-z0-9-]*)\\s+(\\S+)\\s*$/i;

export default function ruleMcpHelp(pi) {
  pi.registerEntryRenderer(HELP_EVENT, (entry, { expanded }, theme) => {
    const data = entry.data ?? {};
    const text = expanded ? data.text : data.text.split("\\n").slice(0, 24).join("\\n");

    return new Text(theme.fg("dim", text));
  });

  // Runs before skill and prompt-template expansion, so the template for
  // /rule-handoff never becomes a user message.
  pi.on("input", async (event, ctx) => {
    const match = CAPTURE.exec(event.text.trim());

    if (!match) {
      return { action: "continue" };
    }

    const text = HELP[match[1]];

    if (!text || !HELP_TOKENS.has(match[2].toLowerCase())) {
      return { action: "continue" };
    }

    pi.appendEntry(HELP_EVENT, { text });

    return { action: "handled" };
  });
}
`;
}

/**
 * opencode's plugin source: one file, auto-discovered from
 * `~/.config/opencode/plugins/`.
 *
 * opencode registers a command by name, and the file templates already own the
 * \`rule-*\` names, so this adds the single \`/rule-help [command]\` entry instead of
 * shadowing them: shadowing would have to reproduce the template for the
 * arguments that are not help, and the TUI exposes no way to submit the prompt
 * from a local command.
 *
 * This surface is not zero-token. \`ctx.session.synthetic\` admits the text as
 * session input and wakes the session (packages/core/src/session/synthetic.ts),
 * so the answer still costs one turn. It is the small turn: the prompt carries
 * the usage block, not the whole file template the body guard would send.
 *
 * @returns {string}
 */
export function opencodeHelpPlugin() {
  return `/**
 * rule-mcp: \`/rule-help [command]\` answered in one small turn.
 *
 * Generated by \`rule-mcp install --agent opencode\` - do not edit, reinstall instead.
 */
import { Plugin } from "@opencode/plugin";

const HELP = ${helpMapSource()};

const LIST = ${commandListSource()};

export default Plugin.define({
  id: "rule-mcp.help",
  async setup(ctx) {
    await ctx.command.transform((editor) => {
      editor.add({
        name: ${JSON.stringify(OPENCODE_HELP_COMMAND)},
        description: "Show a rule-mcp command's usage",
        execute: async ({ sessionID, prompt }) => {
          const target = String(prompt.text ?? "").trim().split(/\\s+/)[0] ?? "";
          const text = HELP[target] ?? LIST;

          // synthetic admits the text and wakes the session, so the reply is one
          // turn - the small one: it carries the usage block alone.
          await ctx.session.synthetic({ sessionID, text: \`Print the block below verbatim and nothing else.\\n\\n\${text}\` });
        },
      });
    });
  },
});
`;
}
