/**
 * @module cli/installers/resume-surface
 *
 * The resume block for a host that can inject context before a run.
 *
 * Pi has no context injection on `session_start`: that event can notify, not
 * seed the transcript. `before_agent_start` can return a message, and a message
 * is what the model reads. So the extension remembers the reason from
 * `session_start` and injects once, on the first user turn after a resume.
 *
 * The block itself is not embedded: it is repository state, so the extension
 * asks the installed CLI for it (`rule-mcp resume`), which runs the verified
 * handon block plus the plan step. A spawn failure degrades to silence, the
 * same way the hook does.
 *
 * @returns {string} the extension source
 */

/** The extension file name under the Pi extensions directory. */
export const RESUME_EXTENSION_FILE = "rule-mcp-resume.js";

export function piResumeExtension() {
  return `/**
 * rule-mcp: seed a resumed session with the verified handoff and the next step.
 *
 * Generated by \`rule-mcp install --agent pi\` - do not edit, reinstall instead.
 */
import { execFileSync } from "node:child_process";

const TIMEOUT_MS = 20000;

/** The block the CLI prints, or "" when it cannot be read in time. */
function resumeBlock(cwd) {
  try {
    return execFileSync("rule-mcp", ["resume", "--dir", cwd], {
      encoding: "utf8",
      timeout: TIMEOUT_MS,
      stdio: ["ignore", "pipe", "ignore"],
      env: { ...process.env, RULE_MCP_NO_AUTOUPDATE: "1", RULE_MCP_NO_RUM: "1" },
    }).trim();
  } catch {
    return "";
  }
}

export default function ruleMcpResume(pi) {
  let resumed = false;
  let injected = false;

  pi.on("session_start", (event) => {
    // Only a resume has something to resume from. A new or forked session
    // starts clean, and a block there would be a page the user did not ask for.
    resumed = event.reason === "resume";
    injected = false;
  });

  pi.on("before_agent_start", (event) => {
    if (!resumed || injected || event.messageType !== "user") {
      return;
    }

    const content = resumeBlock(process.cwd());

    injected = true;

    if (!content) {
      return;
    }

    // display false: the model needs the context, the reader does not need the
    // page printed again on every resume.
    return { message: { customType: "rule-mcp-resume", content, display: false } };
  });
}
`;
}
